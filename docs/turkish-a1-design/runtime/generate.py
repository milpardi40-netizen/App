"""Offline deterministic compiler. Runtime writes are limited to generated Turkish A1 files.
Persian sound hints are approximate, not IPA, recordings or pronunciation certification.
"""
import json,re
from pathlib import Path
from rows import BANK
from checks import CHECKS,DIST
from supplement import GLOSS,NOTES
HERE=Path(__file__).parent
ROOT=HERE.parents[2]
load=lambda p:json.loads(p.read_text())
D=load(HERE.parent/'design.json')['lessons']
B=load(ROOT/'scripts/fixtures/turkish-a1-before.json')
PRE=load(HERE.parent/'runtime-context.json')['preA1']
words=lambda s:re.findall('[a-zçğıöşüâîû]+',s.lower().replace('i̇','i'))
assert len(BANK)==len(CHECKS)==len(DIST)==len(D)==64
from pronunciation import pronounce
CONTENT={};SKILLS={};PRODUCTION={};MIGRATION={};INTRO={}
taught={w for l in PRE for s in l['sentences'] for w in words(s['text'])}
for plan in D:
    id=plan['id'];old=next(l for l in B['core'] if l['id']==id);raw=BANK[id]
    assert len(raw)==len(old['sentences'])==8
    assert len({r[0].lower() for r in raw})==8,id
    rows=[]
    for i,((text,fa,word,meaning),prev) in enumerate(zip(raw,old['sentences'])):
        assert word.lower() in text.lower(),(id,word,text)
        rows.append(dict(id=prev['id'],text=text,fa=fa,pronunciation=pronounce(text),vocabulary=[dict(word=word,meaning=meaning)],pattern=plan['grammarFa']))
        taught.update(words(text))
    # Explicit, contextual glosses, not a blanket exemption from vocabulary closure.
    intro={}
    for text in [*[t['tr'] for t in plan['scene']],plan['listening']['passage'],plan['reading']['passage']]:
        for w in words(text):
            if w not in taught:
                assert w in GLOSS,(id,'missing contextual introduction',w)
                intro[w]=GLOSS[w];taught.add(w)
    INTRO[id]=intro
    scene=[dict(role=t['role'],speaker=t['role'],text=t['tr'],fa=t['fa']) for t in plan['scene']]
    assert len(scene)==len(old['dialogue'])
    skills=[]
    for i,kind in enumerate(['listening','reading']):
        t=plan[kind];choices=[t['answer'],*DIST[id][i]]
        assert len(choices)==3 and len(set(choices))==3,(id,choices)
        rotate=(plan['proposedIndex']+i)%3;choices=choices[rotate:]+choices[:rotate]
        skills.append(dict(kind=kind,passage=t['passage'],promptFa=t['questionFa'],choices=choices,correctIndex=choices.index(t['answer']),explanationFa='پاسخ از همین پیام: '+t['answer']))
    # Meaning + a manually authored structural/situational contrast, retaining two authored slots.
    first=rows[0];choices=[first['fa'],rows[1]['fa'],rows[2]['fa']]
    assert len(set(choices))==3,id
    n=plan['proposedIndex']%3;choices=choices[n:]+choices[:n]
    contrast=CHECKS[id].copy();c=contrast['choices'];n=(n+1)%3;c=c[n:]+c[:n];contrast['choices']=c;contrast['correctIndex']=c.index(CHECKS[id]['choices'][0])
    checks=[dict(promptFa='در همین درس «'+first['text']+'» چه معنایی دارد؟',choices=choices,correctIndex=choices.index(first['fa']),explanationFa=first['text']+' — '+first['fa']),contrast]
    for check in checks:assert len(set(check['choices']))==3 and check['choices'][check['correctIndex']]
    note=NOTES.get(id.removeprefix('tr-l'),'')
    prerequisite='، '.join(next(l['title'] for l in B['core'] if l['id']==x) for x in plan['prerequisiteIds']) or 'سلام و پاسخ Pre-A1'
    teaching='\n'.join(filter(None,[
        'هدف: '+plan['outcomeFa'],'بازیابی آغاز: '+prerequisite,
        'توضیح: '+plan['grammarFa'],note,
        'واژگان مهم: '+plan['vocabularyFa'],
        'قالب‌ها و صورت‌های لازم پیش از تمرین: '+'؛ '.join(f'{w} = {m}' for w,m in intro.items()) if intro else '',
        'مرز کاربرد: '+plan['outOfScopeAndErrorFa'],'شنیدن: '+plan['pronunciationFa'],
        'راهنمای تلفظ فارسی تقریبی است؛ به‌ویژه ı، ö، ü و ğ را با صوت ترکی مقایسه کن؛ این خط، IPA یا ارزیابی بومی نیست.',
        'تولید: '+plan['productionFa']]))
    CONTENT[id]=dict(situation='هدف: '+plan['outcomeFa'],teachingFa=teaching,sentences=rows,dialogue=scene,checks=checks)
    SKILLS[id]=skills
    PRODUCTION[id]=dict(speaking=plan['productionFa'],writing=plan['productionFa'],minWords=3 if plan['proposedIndex']<=6 else 6,checklist=['پیام خواسته‌شده را با واژه‌ها و الگوی همین درس رسانده‌ام','پسوند، حالت اسم و شخص/خطاب را متناسب نگه داشته‌ام؛ جملهٔ اسمی یا ضمیر حذف‌شدهٔ معتبر مجاز است','معنی و زمان پیام‌ها مرتبط‌اند؛ اطلاعات خیالی مجاز است'])
    MIGRATION[id]=[r['id'] for r,p in zip(rows,old['sentences']) if r['text']!=p['text'] or r['fa']!=p['fa']]
def emit(name,value,typ):return 'export const '+name+': '+typ+' = '+json.dumps(value,ensure_ascii=False,indent=2)+';\n'
header="// Generated by docs/turkish-a1-design/runtime/generate.py. Edit authoring sources instead.\nimport type {LearningLesson} from './types';\nimport type {A1SkillTask} from './a1Skills';\nimport type {ProductionPrompt} from '../productionPrompt';\n"
(ROOT/'lib/languages/turkishA1.generated.ts').write_text(header+emit('TURKISH_A1_CONTENT',CONTENT,"Readonly<Record<string, Pick<LearningLesson, 'situation'|'teachingFa'|'sentences'|'dialogue'|'checks'>>>")+emit('TURKISH_A1_SKILLS',SKILLS,'Readonly<Record<string, readonly A1SkillTask[]>>')+emit('TURKISH_A1_PRODUCTION',PRODUCTION,'Readonly<Record<string, ProductionPrompt>>'))
(ROOT/'lib/languages/turkishA1ChangedSlots.generated.json').write_text(json.dumps(MIGRATION,ensure_ascii=False,indent=2)+'\n')
(HERE/'migration.json').write_text(json.dumps(MIGRATION,ensure_ascii=False,indent=2)+'\n')
(HERE/'introduced-forms.json').write_text(json.dumps(INTRO,ensure_ascii=False,indent=2)+'\n')
print(f'Generated 64 Turkish A1 / 512 stable rows / 228 exact scene turns / 128 checks / 128 independent skills / 64 production. Changed slots: {sum(map(len,MIGRATION.values()))}.')
