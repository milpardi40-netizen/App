LETTERS=dict(zip('ABCDEFGHIJKLMNOPQRSTUVWXYZ','آ|بِ|سِ|دِ|اُ|اِف|ژِ|اَش|ای|ژی|کا|اِل|اِم|اِن|اُ|پِ|کو|اِغ|اِس|تِ|او|وِ|دوبلُ‌وِ|ایکس|ایگغِک|زِد'.split('|')))
def fallback(word):
    w=word.lower()
    w=re.sub(r'(aient|ais|ait)$','اِ',w)
    w=re.sub(r'(er|ez)$','ه',w)
    w=re.sub(r'ent$','ان',w)
    w=re.sub(r'[sx]$','',w)
    w=re.sub(r'[tdp]$','',w)
    w=re.sub(r'e$','',w)
    for a,b in [('eaux','او'),('eau','او'),('au','او'),('ou','او'),('oin','وَن'),('ien','یَن'),('ain','اَن'),('ein','اَن'),('an','ان'),('en','ان'),('on','اُن'),('un','اَن'),('oi','وا'),('ch','ش'),('ph','ف'),('gn','نی'),('qu','ک'),('ai','اِ'),('ei','اِ')]:w=w.replace(a,b)
    w=re.sub(r'c(?=[eiéèêy])','س',w);w=re.sub(r'g(?=[eiéèêy])','ژ',w)
    w=re.sub(r'([a-z])\1',r'\1',w)
    chars={'a':'ا','à':'ا','â':'آ','b':'ب','c':'ک','ç':'س','d':'د','e':'ُ','é':'ه','è':'اِ','ê':'اِ','ë':'اِ','f':'ف','g':'گ','h':'','i':'ی','î':'ی','ï':'ی','j':'ژ','k':'ک','l':'ل','m':'م','n':'ن','o':'ُ','ô':'او','œ':'اُ','p':'پ','q':'ک','r':'غ','s':'س','t':'ت','u':'و','ù':'و','û':'و','v':'و','w':'و','x':'کس','y':'ی','z':'ز'}
    return ''.join(chars.get(c,c) for c in w)
def pronounce(text,existing):
    if text in existing:return existing[text]
    s=re.sub(r'\b(?:[A-Z][–-])+[A-Z]\b',lambda m:' '.join(LETTERS[c] for c in m[0] if c in LETTERS),text)
    s=s.replace('aujourd’hui','اوژوغدویی').replace('Aujourd’hui','اوژوغدویی').replace('s’il','سیل').replace('qu’il','کیل')
    s=re.sub(r"\b([jcndmlst])['’]",lambda m:{'j':'ژ','c':'س','n':'ن','d':'د','m':'م','l':'ل','s':'س','t':'ت'}[m[1].lower()]+' ',s,flags=re.I)
    result=[]
    for t in re.findall(r'[A-Za-zÀ-ÿŒœ]+|[\u0600-\u06ff]+|\d+',s):
        if re.search('[\u0600-\u06ff]',t):result.append(t)
        elif t.isdigit():result.append(' '.join(P[['zéro','un','deux','trois','quatre','cinq','six','sept','huit','neuf'][int(c)]] for c in t))
        elif t in LETTERS:result.append(LETTERS[t])
        else:result.append(P.get(t.lower()) or fallback(t))
    p=' '.join(result)
    assert p and not re.search('[a-zà-ÿœ]',p,re.I),(text,p)
    return p
