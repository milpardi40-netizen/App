export function normalizeGuideSearch(text: string): string {
  return text.normalize('NFKC').replace(/ي/g, 'ی').replace(/ك/g, 'ک').replace(/[\u064B-\u065F\u0670\u200c\u200e\u200f]/g, '').replace(/\s+/g, ' ').trim().toLowerCase();
}

export function searchGuide(sections: readonly GuideSection[], query: string): GuideSection[] {
  const terms = normalizeGuideSearch(query).split(' ').filter(Boolean);
  return sections.filter(section => {
    const text = normalizeGuideSearch([section.title, section.summary, section.keywords, ...section.steps, section.tip || ''].join(' '));
    return terms.every(term => text.includes(term));
  });
}
