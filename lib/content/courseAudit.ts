import { computeReadiness, type AuditLesson, type BeginnerCore, type CourseLanguage, type CourseReadiness } from '@/lib/content/readiness';
import type { LearningLesson } from '@/lib/languages/types';
import type { SentenceLesson } from '@/lib/courseContent';
import en from '@/lib/content/frequency/en.json';
import de from '@/lib/content/frequency/de.json';
import fr from '@/lib/content/frequency/fr.json';
import es from '@/lib/content/frequency/es.json';
import ru from '@/lib/content/frequency/ru.json';
import ruBeginner from '@/lib/content/frequency/ru-beginner.json';
import tr from '@/lib/content/frequency/tr.json';
import PACK_COVERAGE_JSON from '@/lib/content/packCoverage.generated.json';
import { CEFR_BANDS, type CefrBand } from '@/lib/content/courseSpec';

/** Top-8000 frequency words per language (wordfreq, sanitised by `curateFrequency.ts`); bundled so readiness works offline. */
export const FREQUENCY: Record<CourseLanguage, readonly string[]> = { en, de, fr, es, ru, tr };

/**
 * Beginner core per language, in teaching order (`scripts/content/genBeginnerFrequency.ts`): the words a
 * band is measured on while its ceiling is inside the core. A course with no core list is measured on the
 * corpus list, exactly as before.
 */
export const BEGINNER_FREQUENCY: Partial<Record<CourseLanguage, BeginnerCore>> = {
  ru: ruBeginner as unknown as BeginnerCore,
};

/** Vocabulary index of the packs published with this APK (generated by `genPackCoverage.ts`). */
export const PACK_COVERAGE: Record<CourseLanguage, Partial<Record<CefrBand, readonly string[]>>> =
  PACK_COVERAGE_JSON as unknown as Record<CourseLanguage, Partial<Record<CefrBand, readonly string[]>>>;
void CEFR_BANDS;

/** Adapter for Russian / Turkish / German / French / Spanish lesson records. */
export function auditLessonsFromLearning(lessons: ReadonlyArray<LearningLesson & { levelId: number }>): AuditLesson[] {
  return lessons.map(lesson => ({
    id: lesson.id, levelId: lesson.levelId, title: lesson.title,
    sentences: lesson.sentences.map(s => ({ text: s.text, pattern: s.pattern })),
    hasDialogue: (lesson.dialogue?.length ?? 0) > 0, checks: lesson.checks?.length ?? 0,
  }));
}

/** Adapter for the English course. */
export function auditLessonsFromEnglish(lessons: readonly SentenceLesson[]): AuditLesson[] {
  return lessons.map(lesson => ({
    id: lesson.id, levelId: lesson.levelId, title: lesson.title,
    sentences: lesson.sentences.map(s => ({ text: s.en, pattern: s.pattern })),
    hasDialogue: (lesson.dialogue?.length ?? 0) > 0,
    // The English lesson shape carries checks only on some lessons; leaving the field out is what tells
    // readiness "this course is not measured on bundled checks".
    ...(Array.isArray((lesson as unknown as { checks?: unknown[] }).checks)
      ? { checks: (lesson as unknown as { checks: unknown[] }).checks.length } : {}),
  }));
}

const cache = new Map<string, CourseReadiness>();
/** Memoised readiness: lesson data is static per build, so each course is computed once. */
/**
 * Memoised readiness for the UI. The headline (`coverage`, and `readiness` through it) is the bundled
 * course only; the vocabulary the published packs add is reported beside it as `coverageWithPacks`, and
 * `includePublishedPacks` (default true) decides whether that second number is computed at all. Scripts
 * that audit bundled lessons alone pass false.
 */
export function courseReadiness(language: CourseLanguage, lessons: readonly AuditLesson[], includePublishedPacks = true): CourseReadiness {
  const key = `${language}:${lessons.length}:${includePublishedPacks}`;
  let value = cache.get(key);
  if (!value) {
    value = computeReadiness(language, lessons, FREQUENCY[language], 60, includePublishedPacks ? PACK_COVERAGE[language] : undefined, {
      beginnerFrequency: BEGINNER_FREQUENCY[language],
    });
    cache.set(key, value);
  }
  return value;
}
