const CONTEXT_WORDS = [
  ['моя́', 'مال من؛ همراه اسم مؤنث'], ['ма́ма', 'مادر'], ['сестра́', 'خواهر'], ['Она́', 'او؛ برای زن'],
  ['Э́то', 'این است؛ برای معرفی'], ['и́ли', 'یا؛ برای انتخاب'], ['Пожа́луйста', 'لطفاً؛ در درخواست'],
  ['твой', 'مال تو؛ همراه اسم مذکر'], ['ваш', 'مال شما؛ همراه اسم مذکر'],
  ['тебя́', 'تو؛ در عبارت «У тебя́ есть»'], ['тебе́', 'به تو؛ اینجا در پرسیدن سن'],
] as const;
const fold = (text: string) => text.toLowerCase().replace(/\u0301/g, '').replace(/ё/g, 'е');

/** Preserve stable IDs and useful vocabulary; attach short usage notes to the actual example. */
export function enrichRussianPreA1(lesson: LearningLesson): LearningLesson {
  const plan = RUSSIAN_PRE_A1_PRACTICAL[lesson.id];
  if (!plan) throw new Error(`Missing authored Pre-A1 plan: ${lesson.id}`);
  const sentences: LearningSentence[] = lesson.sentences.map((sentence, index) => {
    const example = plan.examples?.[index];
    const vocabulary = ['ru-pre-03-family-home:0', 'ru-pre-03-family-home:4', 'ru-pre-05-pronouns-family:1', 'ru-pre-05-pronouns-family:6'].includes(`${lesson.id}:${index}`) ? [] : [...sentence.vocabulary];
    if (example) {
      const tokens: string[] = fold(example[0]).match(/[а-я]+/g) ?? [];
      for (const [word, meaning] of CONTEXT_WORDS) {
        if (tokens.includes(fold(word)) && !vocabulary.some(entry => fold(entry.word) === fold(word))) vocabulary.push({ word, meaning });
      }
    }
    return {
      ...sentence,
      vocabulary,
      ...(example ? { text: example[0], fa: example[1], pronunciation: example[2] } : {}),
      pattern: index === plan.contrast[0] || index === plan.contrast[1]
        ? plan.contrast[2]
        : sentence.pattern,
    };
  });
  const retainedCheck = lesson.checks?.[0];
  if (!retainedCheck) throw new Error(`Missing retained check: ${lesson.id}`);
  const answer = plan.dialogue[1][0];
  return {
    ...lesson,
    situation: `هدف: بتوانم ${plan.goal}\nموقعیت: ${plan.scene}`,
    teachingFa: `${plan.tip}\nتمرین اصلی: ${plan.contrast[2]}\nتمرین بیشتر، اختیاری: گفت‌وگو را با نقش عوض‌شده تکرار کن؛ بار اول با متن، بار دوم با اشارهٔ فارسی و بار آخر از حافظه.`,
    sentences,
    dialogue: plan.dialogue.map(([text, fa, pronunciation], index) => ({
      speaker: index % 2 ? 'زبان‌آموز' : 'هم‌صحبت', role: index % 2 ? 'learner' as const : 'partner' as const,
      text, fa, pronunciation,
    })),
    checks: orderChecks([
      { promptFa: plan.response[0], choices: [answer, ...plan.response.slice(1)], correctIndex: 0, explanationFa: `پاسخ مناسب این موقعیت: «${answer}». ${plan.dialogue[1][1]}` },
      { promptFa: plan.intent[0], choices: [...plan.intent.slice(1)], correctIndex: 0, explanationFa: `کاربرد این عبارت: ${plan.intent[1]}` },
      retainedCheck,
    ], lesson.id),
  };
}
