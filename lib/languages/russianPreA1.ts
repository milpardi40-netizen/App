export const RUSSIAN_PRE_A1_LESSONS: readonly LearningLesson[] = PRE_A1_LESSON_DEFS.map(def => {
  const sentences: LearningSentence[] = def.sentences.map((item, index) => ({
    id: `${def.id}-${String(index + 1).padStart(2, '0')}`,
    text: item.text,
    fa: item.fa,
    pronunciation: item.pronunciation,
    ...(item.pattern ? { pattern: item.pattern } : {}),
    vocabulary: item.vocabulary.map(([word, meaning]) => ({ word, meaning })),
  }));
  return {
    id: def.id,
    title: def.title,
    situation: def.situation,
    durationMinutes: def.durationMinutes,
    teachingFa: def.teachingFa,
    sentences,
    dialogue: def.dialogue.map(turn => ({ ...turn })),
    checks: orderChecks(
      def.checks.map(check => ({
        promptFa: check.promptFa,
        choices: [...check.choices],
        correctIndex: check.correctIndex,
        explanationFa: check.explanationFa,
      })),
      def.id,
    ),
  };
});

export const RUSSIAN_PRE_A1_SUBTITLES: Readonly<Record<string, string>> = Object.fromEntries(
  PRE_A1_LESSON_DEFS.map(lesson => [lesson.id, lesson.subtitle]),
);

const MODULE_BY_LESSON: Readonly<Record<string, string>> = Object.fromEntries(
  PRE_A1_LESSON_DEFS.map(lesson => [lesson.id, lesson.module]),
);

export function russianPreA1ModuleForLesson(lessonId: string): string {
  const module = MODULE_BY_LESSON[lessonId];
  if (!module) throw new Error(`Pre-A1 Russian lesson ${lessonId} has no curriculum module.`);
  return module;
}
