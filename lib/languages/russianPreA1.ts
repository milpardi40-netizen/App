const TARGETS: Record<string,string> = { хочу:'می‌خواهم', хочешь:'می‌خواهی', зовут:'صدا می‌کنند / نام دارند', ищете:'دنبال می‌گردید', вход:'ورودی', выход:'خروجی', справа:'سمت راست', слева:'سمت چپ', прямо:'مستقیم', завтра:'فردا', билет:'بلیت', билета:'بلیت (پس از دو، سه یا چهار)', билетов:'بلیت (شکل جمع در شمارش)', подъезд:'ورودی ساختمان', чай:'چای', воду:'آب (در درخواست)', вода:'آب', суп:'سوپ', сок:'آب‌میوه', стакан:'لیوان', стол:'میز', стул:'صندلی', кот:'گربه', дом:'خانه', школа:'مدرسه', лифт:'آسانسور', кафе:'کافه', центр:'مرکز', меню:'منو', моё:'مال من', твоё:'مال تو', здесь:'اینجا', там:'آنجا', меня:'مرا / من را', я:'من', ты:'تو' };
function target(line: StarterLine) {
  const tokens = line.text.toLowerCase().match(/[а-яё\u0301]+/gu) ?? [];
  const key = Object.keys(TARGETS).find(k => tokens.some(t => t.replace(/\u0301/g,'') === k));
  const word = key && tokens.find(t => t.replace(/\u0301/g,'') === key);
  return key && word ? { word, meaning: TARGETS[key] } : { word: line.text.replace(/[.,?!]+$/, ''), meaning: line.fa };
}
